#!/usr/bin/env bash
# r3dg0d/nixos-installer apps: everyday, gaming, streaming, dev and creative apps on NixOS.
#
#   curl -fsSL https://raw.githubusercontent.com/r3dg0d/nixos-installer/main/apps.sh | sudo bash
#   curl -fsSL .../apps.sh | sudo bash -s -- --no-creative --add discord,spotify
#
# Writes /etc/nixos/r3dg0d-apps.nix, adds it to the imports in configuration.nix once
# (backup: configuration.nix.bak-r3dg0d-apps), checks that it evaluates, then runs
# nixos-rebuild switch. Re-run any time to change the selection. MIT licensed.
set -euo pipefail

NIXOS_DIR="${NI_NIXOS_DIR:-/etc/nixos}"
OUT=""
GAMING=yes STREAMING=yes DEV=yes EVERYDAY=yes CREATIVE=yes
STEAM_REMOTE_PLAY=no STEAM_DEDICATED=no
ADD=""
REPOS=yes
POST_URL="${NI_POST_URL:-https://raw.githubusercontent.com/r3dg0d/nixos-installer/main/post-install.sh}"
SWITCH=yes
CHECK_HOST=yes

usage() {
  cat <<USAGE
apps.sh: install a curated app set system-wide (writes <nixos-dir>/r3dg0d-apps.nix).

  categories (all on by default; --no-X turns one off, --X turns it back on):
    --gaming      Steam, GameMode, Lutris, Heroic, ProtonUp-Qt, MangoHud, Prism Launcher, 32-bit graphics
    --streaming   OBS Studio (+ wlrobs, pipewire audio capture), Vesktop
    --dev         VS Code (unfree), git, gh, rustup, Node.js, Python 3
    --everyday    Firefox, Thunar, mpv, VLC, imv, btop, grim, slurp, wl-clipboard,
                  xdg-desktop-portal-gnome/gtk (niri screen sharing)
    --creative    GIMP, Krita, Blender
    --repos       every r3dg0d repo tool, built by post-install.sh into r3dg0d-repos.nix, with
                  fuzzel launchers (CLI tools open ghostty with --help). NI_BUILD_TIMEOUT, NI_JOBS,
                  NI_CORES and NI_REPOS (comma list) are passed through.
  --steam-remote-play    open the Steam Remote Play firewall ports (default: off)
  --steam-dedicated      open the Steam dedicated server ports  (default: off)
  --add a,b,c            extra nixpkgs attributes (checked before anything changes)
  --nixos-dir DIR        default: /etc/nixos
  --out FILE             default: <nixos-dir>/r3dg0d-apps.nix
  --no-switch            write + verify only
  --no-host-check        allow running off NixOS / as non-root (testing; implies --no-switch)
USAGE
}

while [ $# -gt 0 ]; do
  case "$1" in
    --gaming) GAMING=yes ;;       --no-gaming) GAMING=no ;;
    --streaming) STREAMING=yes ;; --no-streaming) STREAMING=no ;;
    --dev) DEV=yes ;;             --no-dev) DEV=no ;;
    --everyday) EVERYDAY=yes ;;   --no-everyday) EVERYDAY=no ;;
    --repos) REPOS=yes ;;         --no-repos) REPOS=no ;;
    --creative) CREATIVE=yes ;;   --no-creative) CREATIVE=no ;;
    --steam-remote-play) STEAM_REMOTE_PLAY=yes ;;
    --steam-dedicated) STEAM_DEDICATED=yes ;;
    --add) ADD="${ADD:+$ADD,}$2"; shift ;;
    --nixos-dir) NIXOS_DIR="$2"; shift ;;
    --out) OUT="$2"; shift ;;
    --no-switch) SWITCH=no ;;
    --no-host-check) CHECK_HOST=no; SWITCH=no ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1 (see --help)" >&2; exit 2 ;;
  esac
  shift
done
OUT="${OUT:-$NIXOS_DIR/r3dg0d-apps.nix}"
cfg="$NIXOS_DIR/configuration.nix"
say() { printf '%s\n' "$*" >&2; }
die() { say "ERROR: $*"; exit 1; }

if [ "$CHECK_HOST" = yes ]; then
  [ "$(id -u)" -eq 0 ] || die "run as root (sudo)"
  grep -qs '^ID=nixos' /etc/os-release || die "this is not NixOS"
fi
if [ -z "${NIX_PATH:-}" ]; then
  export NIX_PATH="nixpkgs=/nix/var/nix/profiles/per-user/root/channels/nixos:nixos-config=$cfg"
fi

# --add: validate names before writing anything
EXTRA=()
if [ -n "$ADD" ]; then
  IFS=',' read -r -a req <<<"$ADD"
  for p in "${req[@]}"; do
    p="${p// /}"; [ -n "$p" ] || continue
    [[ "$p" =~ ^[A-Za-z0-9_.+-]+$ ]] || die "bad package name: $p"
    nix-instantiate --eval -E "with import <nixpkgs> { config.allowUnfree = true; }; ($p).outPath or ($p).name" >/dev/null 2>&1 \
      || die "'$p' is not a package in this nixpkgs (search: https://search.nixos.org/packages)"
    EXTRA+=("$p")
  done
fi

mkdir -p "$(dirname "$OUT")"
bool() { [ "$1" = yes ] && echo true || echo false; }
{
  echo "# Generated by r3dg0d/nixos-installer apps.sh. Re-run apps.sh to change; edits here are overwritten."
  echo "{ config, lib, pkgs, ... }:"
  echo "{"
  echo "  nixpkgs.config.allowUnfree = true; # steam, vscode"
  echo "  environment.systemPackages = with pkgs; ["
  [ "$GAMING" = yes ]    && echo "    # gaming
    lutris heroic protonup-qt mangohud prismlauncher"
  [ "$STREAMING" = yes ] && echo "    # streaming / voice
    vesktop"
  [ "$DEV" = yes ]       && echo "    # dev
    vscode git gh rustup nodejs python3"
  [ "$EVERYDAY" = yes ]  && echo "    # everyday
    firefox mpv vlc imv btop grim slurp wl-clipboard"
  [ "$CREATIVE" = yes ]  && echo "    # creative
    gimp krita blender"
  [ "${#EXTRA[@]}" -gt 0 ] && echo "    # --add
    ${EXTRA[*]}"
  echo "    desktop-file-utils papirus-icon-theme"
  echo "  ];"
  if [ "$GAMING" = yes ]; then cat <<NIX
  programs.steam = {
    enable = true;
    remotePlay.openFirewall = $(bool "$STEAM_REMOTE_PLAY");
    dedicatedServer.openFirewall = $(bool "$STEAM_DEDICATED");
  };
  programs.gamemode.enable = true;
  hardware.graphics = { enable = true; enable32Bit = true; };
NIX
  fi
  if [ "$STREAMING" = yes ]; then cat <<'NIX'
  programs.obs-studio = {
    enable = true;
    plugins = with pkgs.obs-studio-plugins; [ wlrobs obs-pipewire-audio-capture ];
  };
NIX
  fi
  if [ "$EVERYDAY" = yes ]; then cat <<'NIX'
  programs.thunar.enable = true;
  # screen sharing / file pickers under niri
  xdg.portal = {
    enable = true;
    extraPortals = [ pkgs.xdg-desktop-portal-gnome pkgs.xdg-desktop-portal-gtk ];
  };
NIX
  fi
  cat <<'NIX'
  # launchers (fuzzel) find .desktop files and icons through XDG_DATA_DIRS = .../sw/share
  environment.pathsToLink = [ "/share/applications" "/share/icons" ];
}
NIX
} >"$OUT.tmp"

# ---------- repo tools (shared with post-install.sh; nothing duplicated) ----------
REPOS_OUT="$(dirname "$OUT")/r3dg0d-repos.nix"
if [ "$REPOS" = yes ]; then
  post=""
  if [ -f "${BASH_SOURCE[0]:-}" ]; then post="$(dirname "${BASH_SOURCE[0]}")/post-install.sh"; fi
  if [ -z "$post" ] || [ ! -f "$post" ]; then
    post="$(mktemp)"; curl -fsSL "$POST_URL" -o "$post" || die "could not download $POST_URL"
  fi
  pargs=(--no-switch --no-dotfiles --module-out "$REPOS_OUT")
  [ "$CHECK_HOST" = yes ] || pargs+=(--no-host-check)
  say "building r3dg0d repo tools via post-install.sh (progress below) ..."
  bash "$post" "${pargs[@]}" || die "post-install.sh failed; rerun with --no-repos to skip"
fi

say "checking that the module evaluates ..."
check="$(mktemp)"
if [ "$CHECK_HOST" = yes ] && [ -f "$cfg" ]; then
  base="$cfg"   # evaluate together with the real system config
else
  base='{ fileSystems."/" = { device = "/dev/null"; fsType = "ext4"; }; boot.loader.grub.enable = false; system.stateVersion = "26.05"; }'
fi
cat >"$check" <<NIX
(import <nixpkgs/nixos/lib/eval-config.nix> {
  modules = [ ($base) $OUT.tmp ];
}).config.system.build.toplevel.drvPath
NIX
if ! nix-instantiate --eval "$check" >/dev/null 2>"$check.err"; then
  cat "$check.err" >&2; rm -f "$check" "$check.err" "$OUT.tmp"; die "apps module does not evaluate; nothing changed"
fi
rm -f "$check" "$check.err"
mv "$OUT.tmp" "$OUT"
say "wrote $OUT"

wire() {
  local f="$1"
  if grep -q "${f//./\\.}" "$cfg"; then
    say "configuration.nix already imports $f"
  else
    grep -qE '^[[:space:]]*imports[[:space:]]*=[[:space:]]*\[' "$cfg" || die "no 'imports = [' in $cfg; add ./$f yourself"
    [ -f "$cfg.bak-r3dg0d-apps" ] || cp "$cfg" "$cfg.bak-r3dg0d-apps"
    sed -i -E "0,/^[[:space:]]*imports[[:space:]]*=[[:space:]]*\\[/s//&\\n    .\\/$f/" "$cfg"
    say "added ./$f to imports (backup: $cfg.bak-r3dg0d-apps)"
  fi
}
if [ "$SWITCH" = yes ]; then
  wire "$(basename "$OUT")"
  if [ "$REPOS" = yes ] && [ -f "$REPOS_OUT" ]; then wire "$(basename "$REPOS_OUT")"; fi
  say "nixos-rebuild switch (this downloads a few GB the first time) ..."
  nixos-rebuild switch
  update-desktop-database /run/current-system/sw/share/applications 2>/dev/null || true
  say "done. Log out and back in (or restart niri) so new launchers show up in fuzzel."
else
  say "--no-switch: not touching $cfg"
fi
